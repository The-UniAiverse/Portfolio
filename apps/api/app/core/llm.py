"""Provider-agnostic LLM helper.

Every service must work WITHOUT an LLM (rule-based path). The LLM only adds narrative
polish. Swap providers by changing LLM_PROVIDER in .env — no code changes.
Providers: anthropic, openai, gemini, deepseek (the last two via their OpenAI-compatible
endpoints). LLM_FALLBACK_PROVIDER, if set, is tried when the primary provider fails.

Generation modes (sent by API callers):
  - "rules": deterministic output only; never calls a provider (no cost).
  - "ai":    use the configured provider. If none is configured the request is rejected
             with 503 `ai_unavailable` instead of silently returning rules output.
  - "auto":  legacy behaviour — use the provider when configured, otherwise rules.
Every response reports which path produced the text (`*_source`) so the UI never
presents rules output as AI-written.
"""
from __future__ import annotations
import logging
from typing import Literal
from fastapi import HTTPException
from .config import settings

log = logging.getLogger("uniaiverse.llm")

Mode = Literal["auto", "rules", "ai"]

SYSTEM = (
    "You are a senior AI strategy consultant at uniAIverse. Write concise, concrete, "
    "board-ready prose. No hype. Use the client's numbers. Never invent facts not in the input."
)

AI_FALLBACK_NOTICE = (
    "AI-enhanced mode was requested, but the AI provider did not return a response. "
    "This text was generated by the deterministic rules engine instead."
)


# OpenAI-compatible providers: base URL (None = OpenAI itself), key, model.
OPENAI_COMPATIBLE = {
    "openai": lambda: (None, settings.openai_key, settings.llm_model),
    "gemini": lambda: ("https://generativelanguage.googleapis.com/v1beta/openai/", settings.gemini_key, settings.gemini_model),
    "deepseek": lambda: ("https://api.deepseek.com", settings.deepseek_key, settings.deepseek_model),
}
# Gemini 2.5 models spend output tokens on internal "thinking"; give them headroom so answers aren't cut off.
EXTRA_OUTPUT_TOKENS = {"gemini": 4096}


def _has_key(provider: str) -> bool:
    if provider == "anthropic":
        return bool(settings.anthropic_key)
    if provider in OPENAI_COMPATIBLE:
        return bool(OPENAI_COMPATIBLE[provider]()[1])
    return False


def providers() -> list[str]:
    """Configured providers in the order they are tried: primary, then fallback."""
    chain = [settings.llm_provider, settings.llm_fallback_provider]
    return [p for i, p in enumerate(chain) if _has_key(p) and p not in chain[:i]]


def available() -> bool:
    return bool(providers())


def use_ai(mode: Mode) -> bool:
    """Decide server-side whether this request may call the provider."""
    if mode == "rules":
        return False
    if mode == "ai":
        if not available():
            raise HTTPException(
                status_code=503,
                detail={
                    "code": "ai_unavailable",
                    "message": "AI-enhanced mode is not configured on this server. "
                               "Run the tool in rules-only mode instead.",
                },
            )
        return True
    return available()  # "auto"


def _call(provider: str, prompt: str, max_tokens: int, system: str, timeout: float) -> str | None:
    if provider == "anthropic":
        import anthropic
        client = anthropic.Anthropic(api_key=settings.anthropic_key, timeout=timeout)
        msg = client.messages.create(
            model=settings.llm_model, max_tokens=max_tokens, system=system,
            messages=[{"role": "user", "content": prompt}],
        )
        return "".join(b.text for b in msg.content if getattr(b, "type", "") == "text")
    from openai import OpenAI
    base_url, key, model = OPENAI_COMPATIBLE[provider]()
    client = OpenAI(api_key=key, base_url=base_url, timeout=timeout)
    r = client.chat.completions.create(
        model=model, max_tokens=max_tokens + EXTRA_OUTPUT_TOKENS.get(provider, 0),
        messages=[{"role": "system", "content": system}, {"role": "user", "content": prompt}],
    )
    return r.choices[0].message.content


def complete(prompt: str, max_tokens: int = 1200, system: str | None = None, timeout: float = 45.0) -> str | None:
    """Return model text, or None if no provider configured / every provider failed.
    Callers must always have a deterministic fallback. `system` replaces the default consultant persona."""
    system = system or SYSTEM
    for provider in providers():
        try:
            text = _call(provider, prompt, max_tokens, system, timeout)
            if text and text.strip():
                return text
            log.warning("LLM provider %s returned no text", provider)
        except Exception as exc:  # never let an LLM outage break a deliverable
            # Log the exception type only: provider error messages can echo request details.
            log.warning("LLM call to %s failed (%s)", provider, type(exc).__name__)
    return None
