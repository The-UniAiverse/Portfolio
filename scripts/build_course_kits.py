#!/usr/bin/env python3
"""Build the delivery kit for every course from two sources of truth:
    training-materials/curriculum.yaml  (modules, hours, topics, labs, outcomes)
    training-materials/<course>/demos/NN_*.py  (docstring header: title, minutes, module, Shows, Lab; closing say-line)
Writes per course:  README.md · facilitator-guide.md · exercises.md · handouts/01_key_ideas.md · demos/run_all.py
Hand-written files are never touched: only files that carry the GENERATED marker (or do not exist) are written.
    python scripts/build_course_kits.py            # all courses
    python scripts/build_course_kits.py mlops      # one course (by folder)"""
from __future__ import annotations
import re, sys
from pathlib import Path
import yaml
ROOT = Path(__file__).resolve().parents[1]; MAT = ROOT / "training-materials"
MARK = "<!-- GENERATED by scripts/build_course_kits.py — edit the demo docstrings or curriculum.yaml, then re-run. Delete this line to take the file over by hand. -->"
PYMARK = "# GENERATED by scripts/build_course_kits.py"
SKIP = {"agentic-ai-workshop"}          # the workshop kit is hand-built

def parse_demo(p: Path) -> dict:
    src = p.read_text(); m = re.match(r'\s*"""(.*?)"""', src, re.S); doc = (m.group(1) if m else "").strip(); first = doc.splitlines()[0] if doc else p.stem
    t = re.search(r"Demo\s+(\d+)\s+—\s+(.*?)(?:\s+\((\d+)\s*min\))?(?:\s+·\s+Module\s+([\w+]+))?\s*\.?$", first)
    get = lambda k: (re.search(rf"^{k}:\s*(.+)$", doc, re.M) or [None, ""])[1].strip()
    says = re.findall(r'say\("(.+?)"\)\s*$', src, re.M) or re.findall(r"Say it: '(.+?)'[\\\"]", src)
    return {"file": p.name, "n": int(t.group(1)) if t else int(p.name[:2]), "title": (t.group(2) if t else first).strip(), "minutes": int(t.group(3)) if t and t.group(3) else 10,
            "modules": [int(x) for x in re.findall(r"\d+", t.group(4))] if t and t.group(4) else [], "shows": get("Shows"), "lab": get("Lab"), "say": says[-1] if says else ""}

def write(path: Path, text: str, marker: str = MARK) -> bool:
    if path.exists() and marker not in path.read_text(): return False
    path.parent.mkdir(parents=True, exist_ok=True); path.write_text(text); return True

def clock(mins: int) -> str: return f"{9 + (30 + mins) // 60:02d}:{(30 + mins) % 60:02d}"

def schedule(course: dict, demos: list[dict]) -> list[str]:
    """A timed run sheet. Modules are cut into teach blocks of at most 50 minutes; a break after ~90 minutes,
    lunch once after ~3 hours, and a new day after ~6.5 teaching hours — wherever that falls."""
    segs = []
    for i, m in enumerate(course["modules"], 1):
        mins = int(round(float(m.get("hours") or 0.5) * 60)); md = [d for d in demos if i in d["modules"]]; demo_m = sum(d["minutes"] for d in md)
        lab_m = max(10, int(mins * 0.4)) if (m.get("lab") or md) else 0; teach = max(5, mins - demo_m - lab_m); topics = m.get("topics") or [m["title"]]
        parts = max(1, -(-teach // 50)); per = -(-len(topics) // parts)
        for k in range(parts):
            tp = topics[k * per:(k + 1) * per] or topics[-1:]; label = f"**Module {i} — {m['title']}**" + (f" ({k + 1}/{parts})" if parts > 1 else "")
            segs.append((teach // parts, label, ("Teach: " + ", ".join(tp) + ".") if k * per < len(topics) else "Worked examples and questions on this module's topics; link back to the demo."))
            if k == 0:
                for d in md: segs.append((d["minutes"], f"Demo {d['n']}", f"**Run `python demos/{d['file']}`** — {d['shows']}. Close with: *“{d['say']}”*"))
        if lab_m:
            lab = (m.get("lab") or md[0]["title"]) + " — see `exercises.md`. Walk the room; collect one result per table."
            for k in range(max(1, -(-lab_m // 75))): segs.append((lab_m // max(1, -(-lab_m // 75)), f"Lab {i}" + (f" (part {k + 1})" if lab_m > 75 else ""), lab if k == 0 else "Continue; tables present work in progress at the end."))
    L = []; day = 0; t = since = taught = 0; lunch = False
    def row(mins, seg, what):
        nonlocal t, since; L.append(f"| {clock(t)} | {seg} | {what} |"); t += mins; since += mins
    def new_day():
        nonlocal day, t, since, taught, lunch; day += 1; t = since = taught = 0; lunch = False
        L.extend(([""] if L else []) + [f"## Day {day}", "", "| Time | Segment | What you do and say |", "|---|---|---|"])
        row(10, "Welcome" if day == 1 else "Recap", "Outcomes on the first slide. Ask each table for the one question they want answered; write them on the flipchart." if day == 1 else "Two-minute recap from a participant, not from you.")
    new_day()
    for n, (mins, seg, what) in enumerate(segs):
        if taught + mins > 390 and taught > 0: row(10, "Day close", "Each table: one thing they will use tomorrow. Homework: bring one real example for the next lab."); new_day()
        if not lunch and t >= 170 and len(segs) - n > 1: row(45, "Lunch", ""); lunch = True; since = 0
        elif since >= 85 and len(segs) - n > 1: row(15, "Break", ""); since = 0
        row(mins, seg, what); taught += mins
    row(15, "Close", f"Assessment: {course.get('assessment', 'review of lab outputs')}. Return to the flipchart questions — tick the ones answered.")
    return L

def build(course: dict) -> list[str]:
    d = MAT / course["folder"]; demos = [parse_demo(p) for p in sorted((d / "demos").glob("[0-9][0-9]_*.py"))]
    if not demos: return []
    done = []; title = course["title"]; n = len(demos)
    data = sorted(p.name for p in (d / "demos" / "data").glob("*")) if (d / "demos" / "data").exists() else []
    readme = [MARK, f"# {title} — delivery kit", "", f"*{course['audience']} · {course['hours']} hours · level {course['level']} · certification: {course.get('certification', '—')}*", "",
              "| What | Where | Edit it |", "|---|---|---|", "| Slides | `slides/slides.md` | edit, then `python scripts/build_slides.py` |", f"| Working demos ({n}) — offline; richer with an LLM key | `demos/NN_*.py`, `demos/run_all.py` | plain Python on the shared toolkit `training-materials/labkit/` |"]
    if data: readme.append(f"| Demo data | `demos/data/` ({', '.join(data)}) | replace with the client's own — same format |")
    readme += ["| Trainer's run sheet | `facilitator-guide.md` | regenerate, or delete the marker line and edit by hand |", "| Exercise sheets | `exercises.md` | same |", "| Handout | `handouts/01_key_ideas.md` | same |", "",
               "## You will be able to", ""] + [f"- {o}" for o in course["outcomes"]] + ["", "## Demos", "", "| # | Demo | Module | Min | Shows |", "|---|---|---|---|---|"]
    readme += [f"| {x['n']} | `{x['file']}` | {'+'.join(map(str, x['modules'])) or '—'} | {x['minutes']} | {x['shows']} |" for x in demos]
    readme += ["", "## Run of show", "**One week before:** `python demos/run_all.py` on the laptop you will present from — it must print `ALL DEMOS OK`. Swap `demos/data/` for the client's own examples where you can. Print `exercises.md` per table and the handout per person.",
               "**In the room:** each demo is one command from this folder: `python demos/NN_name.py`. No internet or API key needed. Each ends with a *Say it* line — your closing sentence.",
               "**Live mode:** set `LLM_PROVIDER` and a key in the repo `.env`; demos that benefit then call a real model.", "**In the browser:** every demo also runs from the `/demos` page (section *Course labs*) — useful for sales calls and the website."]
    done += ["README.md"] if write(d / "README.md", "\n".join(readme) + "\n") else []
    fg = [MARK, f"# Facilitator Guide — {title}", "", f"Slides: `slides/slides.md`. Demos: `demos/`. Exercise sheets: `exercises.md`. Every demo runs offline; start times assume 09:30.", "",
          "**One week before:** run `python demos/run_all.py`. Confirm room, projector, one laptop per pair, Wi-Fi. Print exercises and handouts.", ""] + schedule(course, demos) + ["", "## If short on time", "",
          "Keep every demo; shorten the teaching before it. Cut labs to a paired discussion of the lab question rather than dropping them. Never cut the close.", "", "## What can go wrong", "",
          "- **A demo fails on the day** — you ran `run_all.py` last week, so it is the environment: `pip install -r requirements.txt`, then re-run. Screenshots of each output live in nobody's folder: take them after your dry run.",
          "- **No projector / terminal too small** — open `/demos` in a browser and run the same demo from the *Course labs* section.", "- **The room has no laptops** — run labs as table discussions using the printed exercise sheet; you run the script and change the inputs they call out."]
    done += ["facilitator-guide.md"] if write(d / "facilitator-guide.md", "\n".join(fg) + "\n") else []
    ex = [MARK, f"# {title} — Exercise Sheets", "", "Work in tables of 3–4. Each lab ends with something written down that you take back to work.", ""]
    for i, m in enumerate(course["modules"], 1):
        md = [x for x in demos if i in x["modules"]]
        if not (m.get("lab") or md): continue
        ex += [f"## Lab {i} — {m.get('lab') or m['title']}", "", f"*Module {i}: {m['title']} · about {max(10, int(float(m.get('hours') or 0.5) * 60 * 0.4))} minutes*", ""]
        for x in md: ex += [f"**With demo {x['n']}** (`python demos/{x['file']}`): {x['lab']}", ""]
        ex += ["**Write down:** 1) what you tried · 2) what the result was · 3) one thing you will do differently at work this month.", ""]
    done += ["exercises.md"] if write(d / "exercises.md", "\n".join(ex)) else []
    ho = [MARK, f"# {title} — key ideas (one page)", "", "## What you can now do", ""] + [f"- {o}" for o in course["outcomes"]] + ["", "## The sentences to remember", ""] + [f"{x['n']}. **{x['title']}** — “{x['say']}”" for x in demos if x["say"]] + \
         ["", "## Try it again", "", "Every demo from this course runs on your own laptop: `python demos/NN_name.py` inside this course folder, or from the *Course labs* section of the `/demos` page.", "", "*uniAIverse Academy*"]
    done += ["handouts/01_key_ideas.md"] if write(d / "handouts" / "01_key_ideas.md", "\n".join(ho) + "\n") else []
    run_all = f'''{PYMARK}
"""Dry-run every demo of this course before a delivery:  python run_all.py   (must print ALL DEMOS OK)"""
import subprocess, sys, pathlib
HERE = pathlib.Path(__file__).parent
for f in sorted(HERE.glob("[0-9][0-9]_*.py")):
    print(f">>> python {{f.name}}", flush=True)
    r = subprocess.run([sys.executable, f.name], cwd=HERE, stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=240)
    if r.returncode or "Say it" not in r.stdout: print(r.stdout[-800:], r.stderr[-800:]); sys.exit(f"FAILED: {{f.name}}")
print("\\nALL DEMOS OK")
'''
    done += ["demos/run_all.py"] if write(d / "demos" / "run_all.py", run_all, PYMARK) else []
    return done

if __name__ == "__main__":
    cur = yaml.safe_load((MAT / "curriculum.yaml").read_text()); only = set(sys.argv[1:])
    for c in cur["courses"]:
        if c["folder"] in SKIP or (only and c["folder"] not in only): continue
        out = build(c); print(f"{c['folder']:<28} {'wrote ' + ', '.join(out) if out else 'nothing written (no demos, or all files hand-written)'}")
